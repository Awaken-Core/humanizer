import { scopedModel } from "@/lib/db";
import mongoose, { Schema } from "mongoose";

export const AiJobTypes = [
  "AI_DETECTOR",
  "AI_HUMANIZER",
  "AI_SUMMARIZER",
  "AI_IMPROVER",
  "PLAGIARISM_CHECKER",
  "GRAMMAR_CHECKER",
  "ACCURACY_CHECKER",
  "PARAPHRASER",
] as const;
export const AiJobStatuses = [
  "PENDING",
  "PROCESSING",
  "COMPLETED",
  "FAILED",
  "CANCELLED",
] as const;
export const AiJobSources = ["WORKSPACE", "BOARD"] as const;
export const AiJobModes = [
  "natural",
  "academic",
  "professional",
  "casual",
] as const;
export const AiJobIntensities = ["low", "medium", "high"] as const;
export const AiJobTones = [
  "standard",
  "formal",
  "creative",
  "shorten",
  "expand",
] as const;
export const AiJobFocuses = ["vocabulary", "structure", "both"] as const;

const AiJobSchema = new Schema(
  {
    // Better Auth uses string IDs. Anonymous workspace jobs leave this empty.
    userId: {
      type: String,
      ref: "User",
      index: true,
    },
    anonymousId: {
      type: String,
      index: true,
    },
    source: {
      type: String,
      enum: AiJobSources,
      default: "WORKSPACE",
      required: true,
      index: true,
    },
    documentId: {
      type: Schema.Types.ObjectId,
      ref: "Document",
      index: true,
    },
    inputVersionId: {
      type: Schema.Types.ObjectId,
      ref: "DocumentVersion",
    },
    // Which service is being executed?
    type: {
      type: String,
      enum: AiJobTypes,
      required: true,
      index: true,
    },
    // Processing status
    status: {
      type: String,
      enum: AiJobStatuses,
      default: "PENDING",
      index: true,
    },
    // Input configuration
    input: {
      content: {
        type: String,
        required: true,
        maxlength: 15_000,
      },
      language: {
        type: String,
        default: "en",
      },
      mode: {
        type: String,
        enum: AiJobModes,
      },
      intensity: {
        type: String,
        enum: AiJobIntensities,
      },
      tone: {
        type: String,
        enum: AiJobTones,
      },
      focus: {
        type: String,
        enum: AiJobFocuses,
      },
      options: {
        type: Schema.Types.Mixed,
        default: {},
      },
    },
    // Output generated by the service
    result: {
      type: Schema.Types.Mixed,
      default: null,
    },
    // Model/provider information
    model: {
      provider: String,
      name: String,
      version: String,
    },
    // Execution metadata
    metrics: {
      processingTime: Number,
      inputTokens: Number,
      outputTokens: Number,
      creditsUsed: Number,
    },
    error: {
      code: String,
      message: String,
    },
    idempotencyKey: {
      type: String,
    },
    startedAt: Date,
    completedAt: Date,
  },
  { timestamps: true },
);

AiJobSchema.index({ userId: 1, createdAt: -1 });
AiJobSchema.index({ anonymousId: 1, createdAt: -1 });
AiJobSchema.index({ documentId: 1, source: 1, createdAt: -1 });

AiJobSchema.index(
  { userId: 1, idempotencyKey: 1 },
  {
    unique: true,
    partialFilterExpression: {
      userId: { $type: "string" },
      idempotencyKey: { $type: "string" },
    },
  },
);

AiJobSchema.index(
  { anonymousId: 1, idempotencyKey: 1 },
  {
    unique: true,
    partialFilterExpression: {
      anonymousId: { $type: "string" },
      idempotencyKey: { $type: "string" },
    },
  },
);

export const AiJob = scopedModel(
  mongoose.models.AiJob || mongoose.model("AiJob", AiJobSchema)
);
