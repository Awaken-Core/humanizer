"use client";

import React, { useState, useMemo } from "react";
import type { AiDetectionResult } from "@/features/ai-detector/ai-detector.types";
import {
  Bot,
  UserCheck,
  HelpCircle,
  AlertTriangle,
  Sparkles,
  BarChart3,
  AlignLeft,
} from "lucide-react";

interface AiDetectorViewProps {
  result: AiDetectionResult;
  originalText: string;
}

export function AiDetectorView({ result, originalText }: AiDetectorViewProps) {
  const [activeTab, setActiveTab] = useState<"signals" | "highlights" | "summary">("signals");
  const { scores, highlights, wordCount, sentenceCount, summary, processingTimeMs } = result;

  const verdictMeta = useMemo(() => {
    switch (scores.verdict) {
      case "likely_ai":
        return {
          label: "Likely AI-Generated",
          desc: "Multiple structural and vocabulary markers indicate this text was generated by an AI model.",
          color: "rose",
          icon: Bot,
          badgeClass: "bg-rose-500/10 text-rose-600 dark:text-rose-400 border-rose-500/20",
          barColor: "bg-rose-500",
        };
      case "possibly_ai":
        return {
          label: "Possibly AI-Generated",
          desc: "Some patterns suggest artificial generation or heavy AI assistance.",
          color: "amber",
          icon: AlertTriangle,
          badgeClass: "bg-amber-500/10 text-amber-600 dark:text-amber-400 border-amber-500/20",
          barColor: "bg-amber-500",
        };
      case "uncertain":
        return {
          label: "Inconclusive / Mixed",
          desc: "The text contains a blend of typical human writing patterns and formulaic phrasing.",
          color: "purple",
          icon: HelpCircle,
          badgeClass: "bg-purple-500/10 text-purple-600 dark:text-purple-400 border-purple-500/20",
          barColor: "bg-purple-500",
        };
      case "likely_human":
      default:
        return {
          label: "Likely Human-Written",
          desc: "Text exhibits high natural burstiness, dynamic entropy, and authentic human cadence.",
          color: "emerald",
          icon: UserCheck,
          badgeClass: "bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border-emerald-500/20",
          barColor: "bg-emerald-500",
        };
    }
  }, [scores.verdict]);

  // Render highlights on the original text
  const renderedHighlights = useMemo(() => {
    if (!originalText) return null;
    if (highlights.length === 0) {
      return <span>{originalText}</span>;
    }

    const sorted = [...highlights].sort((a, b) => a.startChar - b.startChar);
    const elements: React.ReactNode[] = [];
    let lastIndex = 0;

    sorted.forEach((h, idx) => {
      const start = Math.max(0, Math.min(h.startChar, originalText.length));
      const end = Math.max(start, Math.min(h.endChar, originalText.length));

      if (start > lastIndex) {
        elements.push(
          <span key={`plain-${lastIndex}-${start}`}>
            {originalText.slice(lastIndex, start)}
          </span>
        );
      }

      if (start < end) {
        const spanText = originalText.slice(start, end);
        elements.push(
          <mark
            key={`hl-${idx}-${start}`}
            title={`Confidence: ${Math.round(h.confidence * 100)}% • Reasons: ${h.reasons.join(", ")}`}
            className="cursor-pointer rounded-xs border-b-2 border-amber-500 bg-amber-500/20 px-1 py-0.5 text-amber-900 transition-colors hover:bg-amber-500/30 dark:text-amber-200"
          >
            {spanText}
          </mark>
        );
        lastIndex = end;
      }
    });

    if (lastIndex < originalText.length) {
      elements.push(
        <span key={`plain-${lastIndex}-${originalText.length}`}>
          {originalText.slice(lastIndex)}
        </span>
      );
    }

    return elements;
  }, [originalText, highlights]);

  const VerdictIcon = verdictMeta.icon;

  return (
    <div className="flex h-full flex-col gap-4 text-xs">
      {/* Top AI / Human Probability Gauge */}
      <div className="flex flex-col gap-3 rounded-xl border border-slate-200/80 bg-slate-50/80 p-4 dark:border-white/[0.06] dark:bg-white/[0.02]">
        <div className="flex items-center justify-between gap-4">
          <div className="flex items-center gap-3">
            <div
              className={`flex h-12 w-12 items-center justify-center rounded-xl border ${verdictMeta.badgeClass}`}
            >
              <VerdictIcon className="h-6 w-6" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="text-base font-bold text-slate-900 dark:text-white">
                  {verdictMeta.label}
                </span>
                <span
                  className={`rounded-full border px-2 py-0.5 text-[10px] font-semibold ${verdictMeta.badgeClass}`}
                >
                  {scores.aiProbability}% AI Score
                </span>
              </div>
              <p className="mt-0.5 text-slate-500 dark:text-slate-400">
                {wordCount} words • {sentenceCount} sentences • {processingTimeMs}ms (Decision-based)
              </p>
            </div>
          </div>

          <div className="text-right">
            <span className="text-xs text-slate-500 dark:text-slate-400">Human Content</span>
            <div className="text-lg font-bold text-emerald-600 dark:text-emerald-400">
              {scores.humanProbability}%
            </div>
          </div>
        </div>

        {/* Dual Meter Bar */}
        <div className="relative h-2.5 w-full overflow-hidden rounded-full bg-emerald-500/20">
          <div
            className={`h-full transition-all duration-500 ${verdictMeta.barColor}`}
            style={{ width: `${scores.aiProbability}%` }}
          />
        </div>
      </div>

      {/* Tabs */}
      <div className="flex items-center justify-between border-b border-slate-200/80 pb-2 dark:border-white/[0.06]">
        <div className="inline-flex rounded-lg border border-slate-200 bg-white p-0.5 shadow-2xs dark:border-white/[0.08] dark:bg-[#12141A]">
          <button
            type="button"
            onClick={() => setActiveTab("signals")}
            className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-md font-medium transition-colors ${
              activeTab === "signals"
                ? "bg-[#0070F3] text-white"
                : "text-slate-600 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            <BarChart3 className="h-3 w-3" />
            <span>Detection Signals (5)</span>
          </button>
          <button
            type="button"
            onClick={() => setActiveTab("highlights")}
            className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-md font-medium transition-colors ${
              activeTab === "highlights"
                ? "bg-[#0070F3] text-white"
                : "text-slate-600 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            <AlignLeft className="h-3 w-3" />
            <span>Flagged Sentences ({highlights.length})</span>
          </button>
          <button
            type="button"
            onClick={() => setActiveTab("summary")}
            className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-md font-medium transition-colors ${
              activeTab === "summary"
                ? "bg-[#0070F3] text-white"
                : "text-slate-600 hover:text-slate-900 dark:text-slate-400 dark:hover:text-white"
            }`}
          >
            <Sparkles className="h-3 w-3" />
            <span>Summary</span>
          </button>
        </div>
      </div>

      {/* Content Area */}
      <div className="flex-1 overflow-y-auto">
        {activeTab === "signals" && (
          <div className="space-y-3">
            {scores.signals.map((signal) => {
              const scorePct = Math.round(signal.score * 100);
              const barColor =
                scorePct > 65
                  ? "bg-rose-500"
                  : scorePct > 40
                  ? "bg-amber-500"
                  : "bg-emerald-500";

              return (
                <div
                  key={signal.name}
                  className="rounded-lg border border-slate-200/80 bg-white/80 p-3 dark:border-white/[0.06] dark:bg-[#12141A]/80"
                >
                  <div className="flex items-center justify-between">
                    <span className="font-semibold text-slate-900 dark:text-white">
                      {signal.label}
                    </span>
                    <div className="flex items-center gap-2">
                      <span className="text-[11px] text-slate-500 dark:text-slate-400">
                        Weight: {Math.round(signal.weight * 100)}%
                      </span>
                      <span className="font-bold text-slate-900 dark:text-white">
                        {scorePct}% AI
                      </span>
                    </div>
                  </div>

                  <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-slate-100 dark:bg-white/[0.06]">
                    <div
                      className={`h-full transition-all duration-300 ${barColor}`}
                      style={{ width: `${scorePct}%` }}
                    />
                  </div>

                  <p className="mt-1.5 text-[11px] text-slate-600 dark:text-slate-300">
                    {signal.interpretation}
                  </p>
                </div>
              );
            })}
          </div>
        )}

        {activeTab === "highlights" && (
          <div className="space-y-3">
            <div className="rounded-lg border border-slate-200/60 bg-white/50 p-4 text-sm leading-relaxed text-slate-800 dark:border-white/[0.04] dark:bg-[#101216]/50 dark:text-slate-200">
              {renderedHighlights}
            </div>

            {highlights.length > 0 && (
              <div className="space-y-2">
                <div className="font-semibold text-slate-900 dark:text-white">
                  Identified AI Patterns
                </div>
                {highlights.map((h, i) => (
                  <div
                    key={i}
                    className="flex items-start justify-between gap-3 rounded-md border border-slate-200 bg-white/70 p-2 text-[11px] dark:border-white/[0.06] dark:bg-[#12141A]"
                  >
                    <span className="text-slate-700 dark:text-slate-300">
                      {h.reasons.join(" • ")}
                    </span>
                    <span className="shrink-0 font-medium text-amber-600 dark:text-amber-400">
                      {Math.round(h.confidence * 100)}% confidence
                    </span>
                  </div>
                ))}
              </div>
            )}
          </div>
        )}

        {activeTab === "summary" && (
          <div className="space-y-3 rounded-lg border border-slate-200/80 bg-white/70 p-4 text-slate-800 dark:border-white/[0.06] dark:bg-[#101216]/60 dark:text-slate-200">
            <div className="flex items-center gap-2 font-semibold text-slate-900 dark:text-white">
              <Sparkles className="h-4 w-4 text-[#00B4D8]" />
              <span>Diagnostic Assessment</span>
            </div>
            <div className="whitespace-pre-wrap text-xs leading-relaxed text-slate-600 dark:text-slate-300">
              {summary}
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
